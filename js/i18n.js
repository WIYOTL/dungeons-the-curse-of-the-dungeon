    function translate(value, language = currentLanguage) {
        if (typeof value !== 'string') {
            return value;
        }
        const exact = language === 'en' ? english : french;
        if (exact[value]) return exact[value];

        const normalized = normalize(value);
        const mapped = exact[normalized] || translateDynamic(normalized, language);
        if (mapped === normalized) return value;
        const whitespace = value.match(whitespacePattern);
        return `${whitespace[1]}${mapped}${whitespace[3]}`;
    }

    function translateTextNode(node) {
        const current = node.nodeValue;
        const state = textOriginals.get(node);
        const original = state && state.rendered === current ? state.original : current;
        const translated = translate(original);
        textOriginals.set(node, { original, rendered: translated });
        if (translated !== current) node.nodeValue = translated;
    }

    const translatedAttributes = ['aria-label', 'aria-description', 'title', 'placeholder', 'alt', 'content'];
    function translateElementAttributes(element) {
        let originals = attributeOriginals.get(element);
        if (!originals) {
            originals = new Map();
            attributeOriginals.set(element, originals);
        }
        for (const name of translatedAttributes) {
            if (!element.hasAttribute(name)) continue;
            const current = element.getAttribute(name);
            const state = originals.get(name);
            const original = state && state.rendered === current ? state.original : current;
            const translated = translate(original);
            originals.set(name, { original, rendered: translated });
            if (translated !== current) element.setAttribute(name, translated);
        }
    }

    function translateSubtree(root = document) {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node = walker.nextNode();
        while (node) {
            translateTextNode(node);
            node = walker.nextNode();
        }
        if (root instanceof Element) {
            translateElementAttributes(root);
            root.querySelectorAll('*').forEach(translateElementAttributes);
        } else if (root === document) {
            document.querySelectorAll('*').forEach(translateElementAttributes);
        }
    }

    function detectLanguage() {
        try {
            const saved = localStorage.getItem(LANGUAGE_KEY);
            if (saved === 'en' || saved === 'fr') return saved;
        } catch (error) {
            console.warn('The saved language preference could not be read:', error);
        }
        return /^en(?:-|$)/i.test(navigator.language || '') ? 'en' : 'fr';
    }

    let currentLanguage = detectLanguage();

    function updateLanguageSelects() {
        document.querySelectorAll('[data-language-select]').forEach(select => {
            select.value = currentLanguage;
        });
    }

    function setLanguage(language) {
        if (language !== 'en' && language !== 'fr') {
            throw new RangeError(`Unsupported game language: ${language}`);
        }
        currentLanguage = language;
        document.documentElement.lang = language;
        try {
            localStorage.setItem(LANGUAGE_KEY, language);
        } catch (error) {
            console.warn('The language preference could not be saved:', error);
        }
        updateLanguageSelects();
        translateSubtree();
        window.dispatchEvent(new CustomEvent('dungeons:language-changed', { detail: { language } }));
    }

    window.t = translate;
    window.setGameLanguage = setLanguage;
    window.getGameLanguage = () => currentLanguage;

